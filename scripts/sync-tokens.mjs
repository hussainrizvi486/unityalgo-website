#!/usr/bin/env node
/**
 * Writes lib/design-tokens.generated.ts from the token blocks in app/globals.css.
 *
 * The CSS file is the only place token values are written. HTML email cannot use CSS variables, so server
 * code that builds email reads this generated copy instead of repeating any value. `npm run dev` and
 * `npm run build` run this first; commit the result so deploys that ship without the CSS still work.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const css = readFileSync(join(root, 'app/globals.css'), 'utf8');

function block(selector) {
    // A scope may be declared more than once (e.g. :root also carries the derived values), so read every block.
    const tokens = {};
    let from = 0;
    for (;;) {
        const start = css.indexOf(`\n${selector} {`, from);
        if (start === -1) break;
        const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('\n}', start));
        for (const match of body.matchAll(/^\s*--([a-z0-9-]+):\s*(.+?);\s*(?:\/\*.*\*\/)?$/gm)) tokens[match[1]] = match[2];
        from = start + 1;
    }
    if (!Object.keys(tokens).length) throw new Error(`No ${selector} block in globals.css`);
    return tokens;
}

const base = block(':root');
const dashboard = { ...base, ...block('.dashboard') };
const dark = { ...dashboard, ...block('.dashboard.dark') };
const out = `// Generated by scripts/sync-tokens.mjs from app/globals.css. Do not edit.
export const designTokens = ${JSON.stringify({ site: base, dashboard, dashboardDark: dark }, null, 2)} as const;
`;
writeFileSync(join(root, 'lib/design-tokens.generated.ts'), out);
console.log('design tokens synced');
